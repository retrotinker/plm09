; runtime RT_MUL16 / RT_DIV16 against a table of edge cases
; (expected values computed by Python when this file was written).
; Each vector: X, D, X*D, X/D, X MOD D.  Also checks Y and U survive.
	INCLUDE	harness.inc
	INCLUDE	"plm_rt.asm"

VP	FDB	0
VN	FCB	0

MAIN	LDX	#N_MUL
	JSR	TBEGIN
	LDX	#RT_VEC+1
	LDA	RT_VEC
	STA	VN
ML	STX	VP
	LDY	#$1357
	LDU	#$2468
	LDD	2,X
	LDX	,X
	JSR	RT_MUL16
	LDX	VP
	CMPD	4,X
	BEQ	ML1
	JSR	REPORT
	JSR	PUTNL
ML1	JSR	CHKYU
	INC	T_NUM
	LEAX	10,X
	DEC	VN
	BNE	ML
	JSR	TEND

	LDX	#N_DIV
	JSR	TBEGIN
	LDX	#RT_VEC+1
	LDA	RT_VEC
	STA	VN
DL	STX	VP
	LDY	#$1357
	LDU	#$2468
	LDD	2,X
	LDX	,X
	JSR	RT_DIV16
	PSHS	X
	LDX	VP
	CMPD	6,X
	PULS	D
	BNE	DL0
	CMPD	8,X
	BEQ	DL1
DL0	JSR	REPORT
	JSR	PUTNL
DL1	JSR	CHKYU
	INC	T_NUM
	LEAX	10,X
	DEC	VN
	BNE	DL
	JSR	TEND
	JMP	DONE

; report if Y/U were not preserved
CHKYU	CMPY	#$1357
	BNE	CHKYU1
	CMPU	#$2468
	BEQ	CHKYU2
CHKYU1	JSR	REPORT
	PSHS	X
	LDX	#N_YU
	JSR	PUTS
	PULS	X
CHKYU2	RTS

N_MUL	FCN	"RT_MUL16"
N_DIV	FCN	"RT_DIV16"
N_YU	FCC	" Y/U clobbered"
	FCB	10,0
; X D  X*D  X/D  X MOD D (with X/0 = $FFFF rem X)
RT_VEC	FCB	22
	FDB	$0000,$0000,$0000,$FFFF,$0000
	FDB	$0001,$0000,$0000,$FFFF,$0001
	FDB	$0000,$0001,$0000,$0000,$0000
	FDB	$0001,$0001,$0001,$0001,$0000
	FDB	$00FF,$00FF,$FE01,$0001,$0000
	FDB	$0100,$0100,$0000,$0001,$0000
	FDB	$FFFF,$0001,$FFFF,$FFFF,$0000
	FDB	$0001,$FFFF,$FFFF,$0000,$0001
	FDB	$FFFF,$FFFF,$0001,$0001,$0000
	FDB	$1234,$5678,$0060,$0000,$1234
	FDB	$8000,$0002,$0000,$4000,$0000
	FDB	$00FF,$0101,$FFFF,$0000,$00FF
	FDB	$012C,$00C8,$EA60,$0001,$0064
	FDB	$3039,$0007,$518F,$06E3,$0004
	FDB	$FFFF,$0100,$FF00,$00FF,$00FF
	FDB	$8001,$8000,$8000,$0001,$0001
	FDB	$C350,$9C40,$9400,$0001,$2710
	FDB	$FFFE,$FFFF,$0002,$0000,$FFFE
	FDB	$03E8,$000A,$2710,$0064,$0000
	FDB	$0007,$3039,$518F,$0000,$0007
	FDB	$FFFF,$8000,$8000,$0001,$7FFF
	FDB	$7FFF,$FFFF,$8001,$0000,$7FFF
	END	H_START
