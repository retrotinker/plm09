; 16-bit ALU, MUL, SEX, ABX, LEA flags, 16-bit loads/stores.
; Expected values worked out by hand from the MC6809 datasheet.
	INCLUDE	harness.inc

T	MACRO
	LDX	#\1_N
	JSR	TBEGIN
	LDX	#\1_T
	LDY	#\1_R
	JSR	RUN16
	JSR	TEND
	ENDM

; V D_in,M,CC_in,D_expected,CC_expected,mask
V	MACRO
	FDB	\1,\2
	FCB	\3
	FDB	\4
	FCB	\5,\6
	ENDM

MAIN	T	ADDD
	T	SUBD
	T	CMPD
	T	CMPX
	T	CMPY
	T	CMPU
	T	LDD
	T	LDX
	T	LDY
	T	LDU
	T	LDS
	T	STD
	T	SEX
	T	MUL
	T	ABX
	T	LEAX
	T	EXG
	JMP	DONE

ADDD_N	FCN	"ADDD"
ADDD_R	ADDD	2,X
	RTS
ADDD_T	FCB	4
	V	$7FFF,$0001,$00,$8000,$0A,$0F
	V	$FFFF,$0001,$00,$0000,$05,$0F
	V	$1234,$1111,$01,$2345,$00,$0F
	V	$8000,$8000,$00,$0000,$07,$0F

SUBD_N	FCN	"SUBD"
SUBD_R	SUBD	2,X
	RTS
SUBD_T	FCB	4
	V	$0000,$0001,$00,$FFFF,$09,$0F
	V	$8000,$0001,$00,$7FFF,$02,$0F
	V	$1234,$1234,$00,$0000,$04,$0F
	V	$0100,$00FF,$00,$0001,$00,$0F

; shared by all 16-bit compares: D is unchanged
CMP_T	FCB	4
	V	$1000,$2000,$00,$1000,$09,$0F
	V	$2000,$2000,$00,$2000,$04,$0F
	V	$8000,$0001,$00,$8000,$02,$0F
	V	$0001,$8000,$00,$0001,$0B,$0F

CMPD_N	FCN	"CMPD"
CMPD_R	CMPD	2,X
	RTS
CMPD_T	EQU	CMP_T

CMPX_N	FCN	"CMPX"
CMPX_R	PSHS	X
	LDU	2,X
	TFR	D,X
	PSHS	U
	CMPX	,S++
	PULS	X,PC
CMPX_T	EQU	CMP_T

CMPY_N	FCN	"CMPY"
CMPY_R	PSHS	Y
	LDU	2,X
	TFR	D,Y
	PSHS	U
	CMPY	,S++
	PULS	Y,PC
CMPY_T	EQU	CMP_T

CMPU_N	FCN	"CMPU"
CMPU_R	PSHS	Y
	LDY	2,X
	TFR	D,U
	PSHS	Y
	CMPU	,S++
	PULS	Y,PC
CMPU_T	EQU	CMP_T

; 16-bit loads: N,Z from value, V cleared, C unchanged
LD_T	FCB	2
	V	$5555,$0000,$03,$0000,$05,$0F
	V	$5555,$8000,$00,$8000,$08,$0F

LDD_N	FCN	"LDD"
LDD_R	LDD	2,X
	RTS
LDD_T	EQU	LD_T

LDX_N	FCN	"LDX"
LDX_R	PSHS	X
	LDX	2,X
	TFR	X,D
	PULS	X,PC
LDX_T	EQU	LD_T

LDY_N	FCN	"LDY"
LDY_R	PSHS	Y
	LDY	2,X
	TFR	Y,D
	PULS	Y,PC
LDY_T	EQU	LD_T

LDU_N	FCN	"LDU"
LDU_R	LDU	2,X
	TFR	U,D
	RTS
LDU_T	EQU	LD_T

LDS_N	FCN	"LDS"
LDS_R	TFR	S,U
	LDS	2,X
	TFR	S,D
	TFR	U,S
	RTS
LDS_T	EQU	LD_T

STD_N	FCN	"STD"
STD_R	STD	$6000
	PSHS	CC
	LDD	$6000
	PULS	CC,PC
STD_T	FCB	2
	V	$8000,$0000,$03,$8000,$09,$0F
	V	$0000,$0000,$02,$0000,$04,$0F

; SEX: N,Z from D
SEX_N	FCN	"SEX"
SEX_R	SEX
	RTS
SEX_T	FCB	3
	V	$1280,$0000,$00,$FF80,$08,$0C
	V	$FF7F,$0000,$00,$007F,$00,$0C
	V	$5500,$0000,$00,$0000,$04,$0C

; MUL: D = A*B, Z from D, C = bit 7 of B
MUL_N	FCN	"MUL"
MUL_R	MUL
	RTS
MUL_T	FCB	4
	V	$FFFF,$0000,$00,$FE01,$00,$05
	V	$1010,$0000,$00,$0100,$00,$05
	V	$0055,$0000,$00,$0000,$04,$05
	V	$0C0C,$0000,$00,$0090,$01,$05

; ABX: X += B unsigned, flags untouched
ABX_N	FCN	"ABX"
ABX_R	PSHS	X
	LDX	2,X
	ABX
	TFR	X,D
	PULS	X,PC
ABX_T	FCB	2
	V	$00FF,$1001,$00,$1100,$00,$00
	V	$0080,$0000,$00,$0080,$00,$00

; LEAX sets Z only
LEAX_N	FCN	"LEAX"
LEAX_R	PSHS	X
	TFR	D,X
	LEAX	-1,X
	TFR	X,D
	PULS	X,PC
LEAX_T	FCB	2
	V	$0001,$0000,$00,$0000,$04,$04
	V	$0000,$0000,$04,$FFFF,$00,$04

; EXG A,B then X<->D round trip
EXG_N	FCN	"EXG"
EXG_R	EXG	A,B
	PSHS	X
	TFR	D,X
	LEAX	1,X
	EXG	X,D
	PULS	X,PC
EXG_T	FCB	1
	V	$1234,$0000,$00,$3413,$00,$00
	END	H_START
