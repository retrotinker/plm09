#!/usr/bin/env python3
"""Generate len_ops.asm: every 6809 opcode in every addressing mode, laid out
so execution falls straight through from LEN_BEGIN to LEN_END.

The sim suite runs it with -t and checks that the sequence of (address,
bytes) in the trace equals lwasm's listing for that range, which verifies
the simulator's and disassembler's instruction decoding against lwasm.

Memory safety: after each instruction the index registers, S and DP are
reset, so writes only land in $B000-$DFFF (the code itself runs from $1000
to about $8B00).  Modes whose address depends on A/B/D or on pointers in
scribbled memory are used only by read-only instructions.

Usage: gen_len_ops.py > len_ops.asm
"""

RESET = ["LDX #$C000", "LDY #$C100", "LDU #$C800", "LDS #$D000", "CLRA", "TFR A,DP"]

# indexed forms whose effective address stays inside $B000-$DFFF and that
# never write the pointer words at $B000-$B003
SAFE_IDX = [",X", "5,Y", "-16,U", "15,S", ",X+", ",Y++", ",-U", ",--S",
            "100,X", "-100,Y", "1000,U", "-1000,S", "[$B000]", "[$B000,PCR]",
            "$B100,PCR"]
# extra forms only for instructions that do not write memory
READ_IDX = SAFE_IDX + ["A,X", "B,Y", "D,U", "*,PCR", "[,X]", "[,X++]", "[,--Y]",
                       "[A,X]", "[B,Y]", "[D,U]", "[5,X]", "[100,S]", "[1000,Y]",
                       "[*,PCR]", "[,S]", "-1,X", "0,Y"]

UNARY = ["NEG", "COM", "LSR", "ROR", "ASR", "LSL", "ROL", "DEC", "INC", "TST", "CLR"]
READ8 = ["SUBA", "CMPA", "SBCA", "ANDA", "BITA", "LDA", "EORA", "ADCA", "ORA", "ADDA",
         "SUBB", "CMPB", "SBCB", "ANDB", "BITB", "LDB", "EORB", "ADCB", "ORB", "ADDB"]
READ16 = ["SUBD", "ADDD", "CMPX", "LDX", "LDD", "LDU",
          "CMPD", "CMPY", "LDY", "LDS", "CMPU", "CMPS"]
STORES = ["STA", "STB", "STD", "STX", "STU", "STY", "STS"]
BRANCHES = ["BRA", "BRN", "BHI", "BLS", "BHS", "BLO", "BNE", "BEQ",
            "BVC", "BVS", "BPL", "BMI", "BGE", "BLT", "BGT", "BLE"]

lines = []
label_no = 0


def ins(text):
    lines.append("\t" + text.replace(" ", "\t", 1))


def ins_reset(text):
    ins(text)
    for r in RESET:
        ins(r)


def next_label():
    global label_no
    label_no += 1
    return "N%d" % label_no


def to_next(text):
    """an instruction whose target is the following instruction"""
    lab = next_label()
    ins(text + " " + lab)
    lines.append(lab)


lines += ["; generated by gen_len_ops.py -- do not edit",
          "\tPRAGMA\t6809",
          "\tORG\t$1000",
          "START"]
for r in RESET:
    ins(r)
lines.append("LEN_BEGIN")

for op in UNARY:
    for m in ["<$40", "$C100"] + SAFE_IDX:
        ins_reset("%s %s" % (op, m))
for op in UNARY:
    if op != "JMP":
        ins(op + "A")
        ins(op + "B")
for op in READ8:
    for m in ["#$12", "<$40", "$C100"] + READ_IDX:
        ins_reset("%s %s" % (op, m))
for op in READ16:
    for m in ["#$1234", "<$40", "$C100"] + READ_IDX:
        ins_reset("%s %s" % (op, m))
for op in STORES:
    for m in ["<$40", "$C100"] + SAFE_IDX:
        ins_reset("%s %s" % (op, m))
for r in ["X", "Y", "S", "U"]:
    for m in READ_IDX:
        ins_reset("LEA%s %s" % (r, m))

# control flow that lands on the next instruction
for b in BRANCHES:
    to_next(b)
    to_next("L" + b)
to_next("BSR")
to_next("LBSR")
to_next("JSR")
to_next("JMP")
lab = next_label()
ins("LDX #" + lab)
ins("JMP ,X")
lines.append(lab)
lab = next_label()
ins("JSR [JPTR1,PCR]")  # JPTR1 holds lab
lines.append(lab)
ins("JMP [JPTR2]")
lines.append("JT2")
for r in RESET:
    ins(r)

# inherent and register-postbyte instructions
for t in ["NOP", "DAA", "SEX", "ABX", "MUL", "ORCC #$50", "ANDCC #$AF",
          "PSHS PC,U,Y,X,DP,B,A,CC", "PULS CC,A,B,DP,X,Y,U", "PSHS A", "PULS B",
          "PSHU PC,S,Y,X,DP,B,A,CC", "PULU CC,A,B,DP,X,Y,S", "PSHU D", "PULU X",
          "TFR A,B", "TFR B,A", "TFR D,X", "TFR X,Y", "TFR Y,U", "TFR U,S",
          "TFR S,D", "TFR PC,X", "TFR CC,A", "TFR A,CC", "TFR DP,B", "TFR B,DP",
          "EXG A,B", "EXG X,Y", "EXG D,U", "EXG CC,DP", "EXG S,X"]:
    ins_reset(t)

lines.append("LEN_END")
ins("CLRA")
ins("STA $FF02")
lines += ["",
          "JPTR1\tFDB\t%s" % lab,
          "JPTR2\tEQU\t$B002",
          "\tORG\t$B000",
          "\tFDB\t$B800\t\t; [$B000] target for stores",
          "\tFDB\tJT2",
          "\tEND\tSTART"]
print("\n".join(lines))
