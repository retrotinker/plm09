; All 16 short and 16 long conditional branches against every NZVC
; combination.  Each stub returns A=1 if its branch was taken, else A=0.
; The result for CC=i is collected into bit i of a 16-bit mask.
	INCLUDE	harness.inc

; short and long stubs; the branch target is the LDA #1
SB	MACRO
	\1	*+4
	CLRA
	RTS
	LDA	#1
	RTS
	ENDM
LB	MACRO
	\1	*+6
	CLRA
	RTS
	LDA	#1
	RTS
	ENDM

BMASK	FDB	0
BI	FCB	0

MAIN	LDX	#NAME
	JSR	TBEGIN
	LDX	#BTAB
	LDB	#32
	STB	R_CNT
BRL	CLR	BMASK
	CLR	BMASK+1
	LDA	#15
	STA	BI
BRI	LDA	BI
	PSHS	A
	PULS	CC
	JSR	[,X]
	LSL	BMASK+1
	ROL	BMASK
	ORA	BMASK+1
	STA	BMASK+1
	DEC	BI
	BPL	BRI
	LDD	BMASK
	CMPD	2,X
	BEQ	BROK
	JSR	REPORT
	PSHS	X
	LDX	#S_GOT
	JSR	PUTS
	JSR	PUTHEX16
	JSR	PUTNL
	PULS	X
BROK	INC	T_NUM
	LEAX	4,X
	DEC	R_CNT
	BNE	BRL
	JSR	TEND
; BSR and LBSR backwards and forwards
	LDX	#NAME2
	JSR	TBEGIN
	BSR	RET1
	JSR	CHKA
	FCB	1
	LBSR	RET2
	JSR	CHKA
	FCB	2
	LBRA	FWD
	JSR	CHKA		; skipped
	FCB	$EE
FWD	LDA	#3
	BRA	FWD2
	LDA	#$EE
FWD2	JSR	CHKA
	FCB	3
	JSR	TEND
	JMP	DONE

RET1	LDA	#1
	RTS
RET2	LDA	#2
	RTS

NAME	FCN	"BRANCH"
NAME2	FCN	"BSR"

; stub, expected mask (bit i = taken when NZVC = i)
BTAB	FDB	S_BRA,$FFFF,S_BRN,$0000,S_BHI,$0505,S_BLS,$FAFA
	FDB	S_BHS,$5555,S_BLO,$AAAA,S_BNE,$0F0F,S_BEQ,$F0F0
	FDB	S_BVC,$3333,S_BVS,$CCCC,S_BPL,$00FF,S_BMI,$FF00
	FDB	S_BGE,$CC33,S_BLT,$33CC,S_BGT,$0C03,S_BLE,$F3FC
	FDB	L_BRA,$FFFF,L_BRN,$0000,L_BHI,$0505,L_BLS,$FAFA
	FDB	L_BHS,$5555,L_BLO,$AAAA,L_BNE,$0F0F,L_BEQ,$F0F0
	FDB	L_BVC,$3333,L_BVS,$CCCC,L_BPL,$00FF,L_BMI,$FF00
	FDB	L_BGE,$CC33,L_BLT,$33CC,L_BGT,$0C03,L_BLE,$F3FC

S_BRA	SB	BRA
S_BRN	SB	BRN
S_BHI	SB	BHI
S_BLS	SB	BLS
S_BHS	SB	BHS
S_BLO	SB	BLO
S_BNE	SB	BNE
S_BEQ	SB	BEQ
S_BVC	SB	BVC
S_BVS	SB	BVS
S_BPL	SB	BPL
S_BMI	SB	BMI
S_BGE	SB	BGE
S_BLT	SB	BLT
S_BGT	SB	BGT
S_BLE	SB	BLE
; LBRA is 3 bytes, the rest 4
L_BRA	LBRA	*+5
	CLRA
	RTS
	LDA	#1
	RTS
L_BRN	LB	LBRN
L_BHI	LB	LBHI
L_BLS	LB	LBLS
L_BHS	LB	LBHS
L_BLO	LB	LBLO
L_BNE	LB	LBNE
L_BEQ	LB	LBEQ
L_BVC	LB	LBVC
L_BVS	LB	LBVS
L_BPL	LB	LBPL
L_BMI	LB	LBMI
