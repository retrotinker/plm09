; memory forms: NEG direct, COM extended, INC indexed.
; a -> -a -> ~(-a) = a-1 -> a; COM sets C and INC leaves it set.
MEMOP_N	FCN	"MEMOP"
MEMOP_R	STA	<$40
	NEG	<$40
	LDA	<$40
	STA	$6000
	COM	$6000
	LDA	$6000
	LDU	#$6002
	STA	,U
	INC	,U
	PSHS	CC
	LDA	,U
	PULS	CC
	RTS
MEMOP_T	FCB	2
	FCB	$01,$00,$00,$01,$01,$0F
	FCB	$80,$00,$00,$80,$0B,$0F
